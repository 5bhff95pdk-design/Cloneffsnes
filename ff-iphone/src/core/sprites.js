  'use strict';
  var U = FF.U;
  var S = FF.Spr = {};

  S.norm = function (art) {
    if (art._n) return art;
    var w = 0, i;
    for (i = 0; i < art.rows.length; i++) w = Math.max(w, art.rows[i].length);
    for (i = 0; i < art.rows.length; i++) {
      var r = art.rows[i];
      if (r.length < w) {
        var padL = Math.floor((w - r.length) / 2);
        r = new Array(padL + 1).join('.') + r;
        while (r.length < w) r += '.';
        art.rows[i] = r;
      }
    }
    art._w = w; art._h = art.rows.length; art._n = 1;
    return art;
  };

  S.pal = function (art, v) {
    v = v || {};
    var b = v.base || art.base || '#7fbf6f';
    var a = v.accent || art.accent || '#ffd257';
    var g = v.glow || art.glow || '#8ef0ff';
    return {
      '1': b, '2': U.shade(b, 0.62), '3': U.shade(b, 1.42), '4': a,
      'k': v.line || U.shade(b, 0.28), 'e': v.eye || '#f6f8ff', 'p': v.pupil || '#141826',
      't': v.bone || '#e8e0c8', 'm': v.metal || '#9aa6c4', 'f': g
    };
  };

  S.build = function (art, variant, scale) {
    S.norm(art);
    scale = scale || 1;
    var rows = art.rows, h = art._h, w = art._w;
    var pal = S.pal(art, variant);
    var cv = FF.Gfx.canvas(w * scale, h * scale), g = cv.getContext && cv.getContext('2d');
    if (!g) { cv.width = w * scale; cv.height = h * scale; return cv; }
    for (var y = 0; y < h; y++) for (var x = 0; x < w; x++) {
      var c = pal[rows[y][x]];
      if (!c) continue;
      g.fillStyle = c;
      g.fillRect(x * scale, y * scale, scale, scale);
    }
    return cv;
  };

  S.tint = function (src, color, amount) {
    var cv = FF.Gfx.canvas(src.width, src.height), g = cv.getContext && cv.getContext('2d');
    if (!g || !src.getContext) return src;
    g.drawImage(src, 0, 0);
    try {
      var d = g.getImageData(0, 0, cv.width, cv.height), a = d.data, rgb = U.rgb(color);
      for (var i = 0; i < a.length; i += 4) {
        if (a[i + 3] < 40) continue;
        a[i] = U.lerp(a[i], rgb[0], amount); a[i + 1] = U.lerp(a[i + 1], rgb[1], amount); a[i + 2] = U.lerp(a[i + 2], rgb[2], amount);
      }
      g.putImageData(d, 0, 0);
    } catch (e) { }
    return cv;
  };
  S.scaled = function (src, k) {
    if (k === 1) return src;
    var cv = FF.Gfx.canvas(Math.round(src.width * k), Math.round(src.height * k)), g = cv.getContext && cv.getContext('2d');
    if (!g || !src.getContext) return src;
    g.imageSmoothingEnabled = false;
    g.drawImage(src, 0, 0, cv.width, cv.height);
    return cv;
  };
  S.flip = function (src) {
    var cv = FF.Gfx.canvas(src.width, src.height), g = cv.getContext && cv.getContext('2d');
    if (!g || !src.getContext) return src;
    g.translate(src.width, 0); g.scale(-1, 1); g.drawImage(src, 0, 0);
    return cv;
  };

