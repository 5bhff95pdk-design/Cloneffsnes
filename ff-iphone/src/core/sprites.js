/* ============================================================
   Spr — pixel art défini en code (aucune image externe)
   Charte : '.' = transparent, 'k' = contour,
   '1' couleur de base, '2' ombre, '3' lumière, '4' accent,
   'e' oeil, 'p' pupille, 't' os/dent, 'm' métal, 'f' lueur.
   Largeur normalisée à l'exécution (padding de '.').
   ============================================================ */
